-- Run in a dedicated sandbox account using a user entitled to both administrative roles.
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS EDH_PUBLISHER;
GRANT ROLE EDH_PUBLISHER TO ROLE SYSADMIN;
CREATE ROLE IF NOT EXISTS EDH_OPERATIONS_READER;
GRANT ROLE EDH_OPERATIONS_READER TO ROLE SYSADMIN;
CREATE ROLE IF NOT EXISTS EDH_FINANCE_READER;
GRANT ROLE EDH_FINANCE_READER TO ROLE SYSADMIN;
CREATE ROLE IF NOT EXISTS EDH_EXPERIENCE_READER;
GRANT ROLE EDH_EXPERIENCE_READER TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS EDH_DEMO;
CREATE SCHEMA IF NOT EXISTS EDH_DEMO.LANDING;
CREATE SCHEMA IF NOT EXISTS EDH_DEMO.CURATED;
CREATE SCHEMA IF NOT EXISTS EDH_DEMO.SERVING;
CREATE WAREHOUSE IF NOT EXISTS EDH_DEMO_WH WITH WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE STAGE IF NOT EXISTS EDH_DEMO.LANDING.SYNTHETIC_UPLOAD;
CREATE TABLE IF NOT EXISTS EDH_DEMO.CURATED.CURRENT_PUBLICATION (
  PRODUCT_ID VARCHAR NOT NULL, PUBLICATION_KEY VARCHAR NOT NULL, CONTRACT_VERSION VARCHAR NOT NULL,
  LOCAL_RUN INTEGER NOT NULL, ACCEPTED_AT TIMESTAMP_TZ NOT NULL, SOURCE_SHA256 VARCHAR NOT NULL,
  PARQUET_SHA256 VARCHAR NOT NULL
);

GRANT USAGE ON SCHEMA EDH_DEMO.LANDING TO ROLE EDH_PUBLISHER;
GRANT USAGE ON SCHEMA EDH_DEMO.CURATED TO ROLE EDH_PUBLISHER;
GRANT CREATE TABLE ON SCHEMA EDH_DEMO.LANDING TO ROLE EDH_PUBLISHER;
GRANT READ, WRITE ON STAGE EDH_DEMO.LANDING.SYNTHETIC_UPLOAD TO ROLE EDH_PUBLISHER;
GRANT SELECT, INSERT, UPDATE ON TABLE EDH_DEMO.CURATED.CURRENT_PUBLICATION TO ROLE EDH_PUBLISHER;
GRANT USAGE ON DATABASE EDH_DEMO TO ROLE EDH_PUBLISHER;
GRANT USAGE ON WAREHOUSE EDH_DEMO_WH TO ROLE EDH_PUBLISHER;
GRANT USAGE ON DATABASE EDH_DEMO TO ROLE EDH_OPERATIONS_READER;
GRANT USAGE ON WAREHOUSE EDH_DEMO_WH TO ROLE EDH_OPERATIONS_READER;
GRANT USAGE ON DATABASE EDH_DEMO TO ROLE EDH_FINANCE_READER;
GRANT USAGE ON WAREHOUSE EDH_DEMO_WH TO ROLE EDH_FINANCE_READER;
GRANT USAGE ON DATABASE EDH_DEMO TO ROLE EDH_EXPERIENCE_READER;
GRANT USAGE ON WAREHOUSE EDH_DEMO_WH TO ROLE EDH_EXPERIENCE_READER;

CREATE TABLE IF NOT EXISTS EDH_DEMO.CURATED.SHIPMENT_RELIABILITY (
  PUBLICATION_KEY VARCHAR NOT NULL,
  PERIOD_START DATE NOT NULL,
  REGION VARCHAR NOT NULL,
  CARRIER VARCHAR NOT NULL,
  SHIPMENT_COUNT NUMBER(38,0) NOT NULL,
  ON_TIME_COUNT NUMBER(38,0) NOT NULL,
  ON_TIME_PCT NUMBER(18,2) NOT NULL,
  REPORTING_NOTE VARCHAR
);
GRANT SELECT, INSERT ON TABLE EDH_DEMO.CURATED.SHIPMENT_RELIABILITY TO ROLE EDH_PUBLISHER;
GRANT USAGE ON SCHEMA EDH_DEMO.SERVING TO ROLE EDH_OPERATIONS_READER;
CREATE OR REPLACE SECURE VIEW EDH_DEMO.SERVING.SHIPMENT_RELIABILITY_V1 COPY GRANTS AS
SELECT d.PERIOD_START, d.REGION, d.CARRIER, d.SHIPMENT_COUNT, d.ON_TIME_COUNT, d.ON_TIME_PCT FROM EDH_DEMO.CURATED.SHIPMENT_RELIABILITY d
JOIN EDH_DEMO.CURATED.CURRENT_PUBLICATION p ON p.PUBLICATION_KEY = d.PUBLICATION_KEY
WHERE p.PRODUCT_ID = 'shipment-reliability';
GRANT SELECT ON VIEW EDH_DEMO.SERVING.SHIPMENT_RELIABILITY_V1 TO ROLE EDH_OPERATIONS_READER;
CREATE OR REPLACE SECURE VIEW EDH_DEMO.SERVING.SHIPMENT_RELIABILITY_V1_1 COPY GRANTS AS
SELECT d.PERIOD_START, d.REGION, d.CARRIER, d.SHIPMENT_COUNT, d.ON_TIME_COUNT, d.ON_TIME_PCT, d.REPORTING_NOTE FROM EDH_DEMO.CURATED.SHIPMENT_RELIABILITY d
JOIN EDH_DEMO.CURATED.CURRENT_PUBLICATION p ON p.PUBLICATION_KEY = d.PUBLICATION_KEY
WHERE p.PRODUCT_ID = 'shipment-reliability' AND p.CONTRACT_VERSION = '1.1.0';
GRANT SELECT ON VIEW EDH_DEMO.SERVING.SHIPMENT_RELIABILITY_V1_1 TO ROLE EDH_OPERATIONS_READER;

