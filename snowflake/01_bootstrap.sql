);

CREATE TABLE IF NOT EXISTS EDH_DEMO.GOVERNANCE.CURRENT_PUBLICATION (
  PRODUCT_ID VARCHAR NOT NULL,
  PUBLICATION_KEY VARCHAR NOT NULL,
  BATCH_ID VARCHAR NOT NULL,
  CONTRACT_VERSION VARCHAR NOT NULL,
  ACCEPTED_AT TIMESTAMP_LTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS EDH_DEMO.GOVERNANCE.PUBLICATION_AUDIT (
  PRODUCT_ID VARCHAR NOT NULL,
  BATCH_ID VARCHAR NOT NULL,
  RESULT VARCHAR NOT NULL,
  DETAILS VARCHAR,
  RECORDED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS EDH_DEMO.CURATED.SHIPMENT_RELIABILITY (
  PUBLICATION_KEY VARCHAR NOT NULL, BATCH_ID VARCHAR NOT NULL,
  PERIOD_START DATE NOT NULL, REGION VARCHAR NOT NULL, CARRIER VARCHAR NOT NULL,
  SHIPMENT_COUNT NUMBER(38,0) NOT NULL, ON_TIME_COUNT NUMBER(38,0) NOT NULL,
  ON_TIME_PCT NUMBER(18,2) NOT NULL, REPORTING_NOTE VARCHAR
);
CREATE TABLE IF NOT EXISTS EDH_DEMO.CURATED.FREIGHT_SPEND (
  PUBLICATION_KEY VARCHAR NOT NULL, BATCH_ID VARCHAR NOT NULL,
  PERIOD_START DATE NOT NULL, REGION VARCHAR NOT NULL, CARRIER VARCHAR NOT NULL,
  SHIPMENT_COUNT NUMBER(38,0) NOT NULL, FREIGHT_CENTS NUMBER(38,0) NOT NULL,
  AVG_COST_EUR NUMBER(18,2) NOT NULL, REPORTING_NOTE VARCHAR
);
CREATE TABLE IF NOT EXISTS EDH_DEMO.CURATED.RETURNS_PULSE (
  PUBLICATION_KEY VARCHAR NOT NULL, BATCH_ID VARCHAR NOT NULL,
  PERIOD_START DATE NOT NULL, CHANNEL VARCHAR NOT NULL, REASON VARCHAR NOT NULL,
  RETURN_COUNT NUMBER(38,0) NOT NULL, REFUND_CENTS NUMBER(38,0) NOT NULL,
  REPORTING_NOTE VARCHAR
);

-- Upgrade of a former optional Serving sandbox: add native batch lineage without deleting old rows.
ALTER TABLE EDH_DEMO.CURATED.SHIPMENT_RELIABILITY ADD COLUMN IF NOT EXISTS BATCH_ID VARCHAR;
ALTER TABLE EDH_DEMO.CURATED.FREIGHT_SPEND ADD COLUMN IF NOT EXISTS BATCH_ID VARCHAR;
ALTER TABLE EDH_DEMO.CURATED.RETURNS_PULSE ADD COLUMN IF NOT EXISTS BATCH_ID VARCHAR;

CREATE OR REPLACE SECURE VIEW EDH_DEMO.SERVING.SHIPMENT_RELIABILITY_V1 AS
SELECT D.PERIOD_START, D.REGION, D.CARRIER, D.SHIPMENT_COUNT, D.ON_TIME_COUNT, D.ON_TIME_PCT
FROM EDH_DEMO.CURATED.SHIPMENT_RELIABILITY D
JOIN EDH_DEMO.GOVERNANCE.CURRENT_PUBLICATION P
  ON D.PUBLICATION_KEY = P.PUBLICATION_KEY AND P.PRODUCT_ID = 'shipment-reliability';
CREATE OR REPLACE SECURE VIEW EDH_DEMO.SERVING.FREIGHT_SPEND_V1 AS
SELECT D.PERIOD_START, D.REGION, D.CARRIER, D.SHIPMENT_COUNT, D.FREIGHT_CENTS, D.AVG_COST_EUR
FROM EDH_DEMO.CURATED.FREIGHT_SPEND D
JOIN EDH_DEMO.GOVERNANCE.CURRENT_PUBLICATION P
  ON D.PUBLICATION_KEY = P.PUBLICATION_KEY AND P.PRODUCT_ID = 'freight-spend';
CREATE OR REPLACE SECURE VIEW EDH_DEMO.SERVING.RETURNS_PULSE_V1 AS
SELECT D.PERIOD_START, D.CHANNEL, D.REASON, D.RETURN_COUNT, D.REFUND_CENTS
FROM EDH_DEMO.CURATED.RETURNS_PULSE D
JOIN EDH_DEMO.GOVERNANCE.CURRENT_PUBLICATION P
  ON D.PUBLICATION_KEY = P.PUBLICATION_KEY AND P.PRODUCT_ID = 'returns-pulse';

