  FILE_FORMAT = EDH_DEMO.RAW.JSON_LINES;
CREATE TABLE IF NOT EXISTS EDH_DEMO.RAW.EVENTS (
  SOURCE_ID VARCHAR NOT NULL,
  BATCH_ID VARCHAR NOT NULL,
  PAYLOAD VARIANT NOT NULL,
  SOURCE_FILE VARCHAR,
