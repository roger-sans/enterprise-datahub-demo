-- Native Snowflake transforms, governed publication and schedules.
-- Run after snowflake/01_bootstrap.sql as SYSADMIN in the dedicated demo account.
USE ROLE SYSADMIN;
USE WAREHOUSE EDH_DEMO_WH;
USE DATABASE EDH_DEMO;

-- Silver: normalized, typed, deterministic latest-revision source observations.
-- These are Snowflake views over staged RAW VARIANT events, not local Parquet jobs.
CREATE OR REPLACE VIEW EDH_DEMO.SILVER.DISPATCH_EVENTS AS
SELECT BATCH_ID,
       PAYLOAD:ref::VARCHAR AS REF,
       TRY_TO_DATE(PAYLOAD:sent_on::VARCHAR) AS SENT_ON,
       TRY_TO_DATE(PAYLOAD:promised_on::VARCHAR) AS PROMISED_ON,
       TRY_TO_DATE(PAYLOAD:delivered_on::VARCHAR) AS DELIVERED_ON,
       UPPER(TRIM(PAYLOAD:region::VARCHAR)) AS REGION,
       TRIM(PAYLOAD:carrier::VARCHAR) AS CARRIER,
       TRY_TO_NUMBER(PAYLOAD:freight_cents::VARCHAR)::NUMBER(38,0) AS FREIGHT_CENTS,
       TRY_TO_NUMBER(PAYLOAD:revision::VARCHAR)::NUMBER(38,0) AS REVISION
FROM EDH_DEMO.RAW.EVENTS
WHERE SOURCE_ID = 'Dispatch events'
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY BATCH_ID, PAYLOAD:ref::VARCHAR
  ORDER BY TRY_TO_NUMBER(PAYLOAD:revision::VARCHAR) DESC,
           TRY_TO_NUMBER(PAYLOAD:source_row::VARCHAR) DESC, SOURCE_ROW DESC
) = 1;

CREATE OR REPLACE VIEW EDH_DEMO.SILVER.RETURN_EVENTS AS
SELECT BATCH_ID,
       PAYLOAD:ref::VARCHAR AS REF,
       TRY_TO_DATE(PAYLOAD:opened_on::VARCHAR) AS OPENED_ON,
       LOWER(TRIM(PAYLOAD:channel::VARCHAR)) AS CHANNEL,
       TRIM(PAYLOAD:reason::VARCHAR) AS REASON,
       TRY_TO_NUMBER(PAYLOAD:refund_cents::VARCHAR)::NUMBER(38,0) AS REFUND_CENTS,
       TRY_TO_NUMBER(PAYLOAD:revision::VARCHAR)::NUMBER(38,0) AS REVISION
FROM EDH_DEMO.RAW.EVENTS
WHERE SOURCE_ID = 'Return events'
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY BATCH_ID, PAYLOAD:ref::VARCHAR
  ORDER BY TRY_TO_NUMBER(PAYLOAD:revision::VARCHAR) DESC,
           TRY_TO_NUMBER(PAYLOAD:source_row::VARCHAR) DESC, SOURCE_ROW DESC
) = 1;

-- Gold: three independent versioned business grains.
-- DAYOFWEEKISO avoids session-dependent WEEK_START settings.
CREATE OR REPLACE VIEW EDH_DEMO.GOLD.SHIPMENT_RELIABILITY AS
SELECT BATCH_ID,
       DATEADD('day', 1 - DAYOFWEEKISO(DELIVERED_ON), DELIVERED_ON)::DATE AS PERIOD_START,
       REGION, CARRIER,
       COUNT(*)::NUMBER(38,0) AS SHIPMENT_COUNT,
       COUNT_IF(DELIVERED_ON <= PROMISED_ON)::NUMBER(38,0) AS ON_TIME_COUNT,
       ROUND(100.0 * COUNT_IF(DELIVERED_ON <= PROMISED_ON) / NULLIF(COUNT(*),0),2)::NUMBER(18,2) AS ON_TIME_PCT
FROM EDH_DEMO.SILVER.DISPATCH_EVENTS
WHERE DELIVERED_ON IS NOT NULL
GROUP BY 1,2,3,4;

CREATE OR REPLACE VIEW EDH_DEMO.GOLD.FREIGHT_SPEND AS
SELECT BATCH_ID,
       DATE_TRUNC('MONTH', SENT_ON)::DATE AS PERIOD_START, REGION, CARRIER,
       COUNT(*)::NUMBER(38,0) AS SHIPMENT_COUNT,
       SUM(FREIGHT_CENTS)::NUMBER(38,0) AS FREIGHT_CENTS,
       ROUND(SUM(FREIGHT_CENTS) / NULLIF(100.0 * COUNT(*),0),2)::NUMBER(18,2) AS AVG_COST_EUR
FROM EDH_DEMO.SILVER.DISPATCH_EVENTS
GROUP BY 1,2,3,4;

CREATE OR REPLACE VIEW EDH_DEMO.GOLD.RETURNS_PULSE AS
SELECT BATCH_ID,
       DATEADD('day', 1 - DAYOFWEEKISO(OPENED_ON), OPENED_ON)::DATE AS PERIOD_START,
       CHANNEL, REASON, COUNT(*)::NUMBER(38,0) AS RETURN_COUNT,
       SUM(REFUND_CENTS)::NUMBER(38,0) AS REFUND_CENTS
FROM EDH_DEMO.SILVER.RETURN_EVENTS
GROUP BY 1,2,3,4;

-- One controlled publisher shared by all three contracts. No arbitrary SQL
-- identifiers are derived from request parameters. No insecure direct writes.
CREATE OR REPLACE PROCEDURE EDH_DEMO.GOVERNANCE.PUBLISH_PRODUCT(
  P_PRODUCT_ID VARCHAR, P_BATCH_ID VARCHAR
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_SOURCE VARCHAR;
  V_SOURCE_ROWS NUMBER DEFAULT 0;
  V_INVALID NUMBER DEFAULT 0;
  V_GOLD_ROWS NUMBER DEFAULT 0;
  V_EXPECTED NUMBER DEFAULT 0;
  V_OBSERVED NUMBER DEFAULT 0;
  V_LATEST VARCHAR;
  V_EXISTING NUMBER DEFAULT 0;
  V_KEY VARCHAR;
BEGIN
  IF (P_PRODUCT_ID = 'shipment-reliability' OR P_PRODUCT_ID = 'freight-spend') THEN
    V_SOURCE := 'Dispatch events';
  ELSEIF (P_PRODUCT_ID = 'returns-pulse') THEN
    V_SOURCE := 'Return events';
  ELSE
    RETURN 'UNKNOWN_PRODUCT';
  END IF;

  SELECT COUNT(*) INTO :V_SOURCE_ROWS FROM EDH_DEMO.RAW.EVENTS
   WHERE SOURCE_ID = :V_SOURCE;
  IF (V_SOURCE_ROWS = 0) THEN
    RETURN 'NO_SOURCE_DATA';
  END IF;

  SELECT BATCH_ID INTO :V_LATEST
    FROM EDH_DEMO.RAW.EVENTS WHERE SOURCE_ID = :V_SOURCE
   GROUP BY BATCH_ID ORDER BY MAX(LOADED_AT) DESC, BATCH_ID DESC LIMIT 1;
  IF (V_LATEST <> P_BATCH_ID) THEN
    RETURN 'BLOCKED_STALE_BATCH';
  END IF;

  IF (V_SOURCE = 'Dispatch events') THEN
    SELECT COUNT(*) INTO :V_SOURCE_ROWS FROM EDH_DEMO.SILVER.DISPATCH_EVENTS
      WHERE BATCH_ID = :P_BATCH_ID;
    SELECT COUNT(*) INTO :V_INVALID FROM EDH_DEMO.SILVER.DISPATCH_EVENTS
     WHERE BATCH_ID = :P_BATCH_ID AND
       (REF IS NULL OR REVISION IS NULL OR SENT_ON IS NULL OR PROMISED_ON IS NULL
        OR REGION IS NULL OR REGION NOT IN ('NORTH','WEST','CENTRAL','COASTAL')
        OR CARRIER IS NULL OR CARRIER = '' OR FREIGHT_CENTS IS NULL OR FREIGHT_CENTS < 0
        OR PROMISED_ON < SENT_ON OR (DELIVERED_ON IS NOT NULL AND DELIVERED_ON < SENT_ON));
  ELSE
    SELECT COUNT(*) INTO :V_SOURCE_ROWS FROM EDH_DEMO.SILVER.RETURN_EVENTS
      WHERE BATCH_ID = :P_BATCH_ID;
    SELECT COUNT(*) INTO :V_INVALID FROM EDH_DEMO.SILVER.RETURN_EVENTS
     WHERE BATCH_ID = :P_BATCH_ID AND
       (REF IS NULL OR REVISION IS NULL OR OPENED_ON IS NULL
        OR CHANNEL NOT IN ('web','store','partner') OR CHANNEL IS NULL
        OR REASON IS NULL OR REASON NOT IN ('Damaged','Wrong item','Unwanted','Late arrival')
        OR REFUND_CENTS IS NULL OR REFUND_CENTS < 0);
  END IF;

  IF (V_SOURCE_ROWS = 0 OR V_INVALID > 0) THEN
    INSERT INTO EDH_DEMO.GOVERNANCE.PUBLICATION_AUDIT (PRODUCT_ID,BATCH_ID,RESULT,DETAILS)
      VALUES (:P_PRODUCT_ID,:P_BATCH_ID,'BLOCKED','Silver source integrity or monetary quality');
    RETURN 'BLOCKED_SILVER_QUALITY';
  END IF;

  IF (P_PRODUCT_ID = 'shipment-reliability') THEN
    SELECT COUNT(*), COALESCE(SUM(SHIPMENT_COUNT),0) INTO :V_GOLD_ROWS,:V_OBSERVED
      FROM EDH_DEMO.GOLD.SHIPMENT_RELIABILITY WHERE BATCH_ID = :P_BATCH_ID;
    SELECT COUNT(*) INTO :V_EXPECTED FROM EDH_DEMO.SILVER.DISPATCH_EVENTS
      WHERE BATCH_ID = :P_BATCH_ID AND DELIVERED_ON IS NOT NULL;
    SELECT COUNT(*) INTO :V_INVALID FROM EDH_DEMO.GOLD.SHIPMENT_RELIABILITY
      WHERE BATCH_ID = :P_BATCH_ID AND (PERIOD_START IS NULL OR REGION IS NULL
      OR CARRIER IS NULL OR SHIPMENT_COUNT <= 0 OR ON_TIME_COUNT < 0
      OR ON_TIME_COUNT > SHIPMENT_COUNT OR ON_TIME_PCT NOT BETWEEN 0 AND 100);
  ELSEIF (P_PRODUCT_ID = 'freight-spend') THEN
    SELECT COUNT(*), COALESCE(SUM(FREIGHT_CENTS),0) INTO :V_GOLD_ROWS,:V_OBSERVED
      FROM EDH_DEMO.GOLD.FREIGHT_SPEND WHERE BATCH_ID = :P_BATCH_ID;
    SELECT COALESCE(SUM(FREIGHT_CENTS),0) INTO :V_EXPECTED
      FROM EDH_DEMO.SILVER.DISPATCH_EVENTS WHERE BATCH_ID = :P_BATCH_ID;
    SELECT COUNT(*) INTO :V_INVALID FROM EDH_DEMO.GOLD.FREIGHT_SPEND
      WHERE BATCH_ID = :P_BATCH_ID AND (PERIOD_START IS NULL OR REGION IS NULL
      OR CARRIER IS NULL OR SHIPMENT_COUNT <= 0 OR FREIGHT_CENTS < 0 OR AVG_COST_EUR < 0);
  ELSE
    SELECT COUNT(*), COALESCE(SUM(REFUND_CENTS),0) INTO :V_GOLD_ROWS,:V_OBSERVED
      FROM EDH_DEMO.GOLD.RETURNS_PULSE WHERE BATCH_ID = :P_BATCH_ID;
    SELECT COALESCE(SUM(REFUND_CENTS),0) INTO :V_EXPECTED
      FROM EDH_DEMO.SILVER.RETURN_EVENTS WHERE BATCH_ID = :P_BATCH_ID;
    SELECT COUNT(*) INTO :V_INVALID FROM EDH_DEMO.GOLD.RETURNS_PULSE
      WHERE BATCH_ID = :P_BATCH_ID AND (PERIOD_START IS NULL OR CHANNEL IS NULL
      OR REASON IS NULL OR RETURN_COUNT <= 0 OR REFUND_CENTS < 0);
  END IF;

  IF (V_GOLD_ROWS = 0 OR V_OBSERVED <> V_EXPECTED OR V_INVALID > 0) THEN
    INSERT INTO EDH_DEMO.GOVERNANCE.PUBLICATION_AUDIT (PRODUCT_ID,BATCH_ID,RESULT,DETAILS)
      VALUES (:P_PRODUCT_ID,:P_BATCH_ID,'BLOCKED','Gold contract or reconciliation failure');
    RETURN 'BLOCKED_GOLD_CONTRACT';
  END IF;

  SELECT COUNT(*) INTO :V_EXISTING FROM EDH_DEMO.GOVERNANCE.CURRENT_PUBLICATION
   WHERE PRODUCT_ID = :P_PRODUCT_ID AND BATCH_ID = :P_BATCH_ID;
  IF (V_EXISTING > 0) THEN
    RETURN 'UNCHANGED';
  END IF;

  V_KEY := SHA2(P_PRODUCT_ID || '|' || P_BATCH_ID, 256);

  BEGIN TRANSACTION;
  IF (P_PRODUCT_ID = 'shipment-reliability') THEN
    INSERT INTO EDH_DEMO.CURATED.SHIPMENT_RELIABILITY
      (PUBLICATION_KEY,BATCH_ID,PERIOD_START,REGION,CARRIER,SHIPMENT_COUNT,ON_TIME_COUNT,ON_TIME_PCT)
    SELECT :V_KEY,BATCH_ID,PERIOD_START,REGION,CARRIER,SHIPMENT_COUNT,ON_TIME_COUNT,ON_TIME_PCT
      FROM EDH_DEMO.GOLD.SHIPMENT_RELIABILITY WHERE BATCH_ID = :P_BATCH_ID;
  ELSEIF (P_PRODUCT_ID = 'freight-spend') THEN
    INSERT INTO EDH_DEMO.CURATED.FREIGHT_SPEND
      (PUBLICATION_KEY,BATCH_ID,PERIOD_START,REGION,CARRIER,SHIPMENT_COUNT,FREIGHT_CENTS,AVG_COST_EUR)
    SELECT :V_KEY,BATCH_ID,PERIOD_START,REGION,CARRIER,SHIPMENT_COUNT,FREIGHT_CENTS,AVG_COST_EUR
      FROM EDH_DEMO.GOLD.FREIGHT_SPEND WHERE BATCH_ID = :P_BATCH_ID;
  ELSE
    INSERT INTO EDH_DEMO.CURATED.RETURNS_PULSE
      (PUBLICATION_KEY,BATCH_ID,PERIOD_START,CHANNEL,REASON,RETURN_COUNT,REFUND_CENTS)
    SELECT :V_KEY,BATCH_ID,PERIOD_START,CHANNEL,REASON,RETURN_COUNT,REFUND_CENTS
      FROM EDH_DEMO.GOLD.RETURNS_PULSE WHERE BATCH_ID = :P_BATCH_ID;
  END IF;

  MERGE INTO EDH_DEMO.GOVERNANCE.CURRENT_PUBLICATION T
  USING (SELECT :P_PRODUCT_ID AS PRODUCT_ID, :V_KEY AS PUBLICATION_KEY,
                :P_BATCH_ID AS BATCH_ID, '1.0.0' AS CONTRACT_VERSION) S
    ON T.PRODUCT_ID = S.PRODUCT_ID
  WHEN MATCHED THEN UPDATE SET PUBLICATION_KEY = S.PUBLICATION_KEY,
    BATCH_ID = S.BATCH_ID, CONTRACT_VERSION = S.CONTRACT_VERSION,
    ACCEPTED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (PRODUCT_ID,PUBLICATION_KEY,BATCH_ID,CONTRACT_VERSION,ACCEPTED_AT)
    VALUES (S.PRODUCT_ID,S.PUBLICATION_KEY,S.BATCH_ID,S.CONTRACT_VERSION,CURRENT_TIMESTAMP());

  INSERT INTO EDH_DEMO.GOVERNANCE.PUBLICATION_AUDIT
    (PRODUCT_ID,BATCH_ID,RESULT,DETAILS)
    VALUES (:P_PRODUCT_ID,:P_BATCH_ID,'PUBLISHED','Silver and Gold gates passed');
  COMMIT;
  RETURN 'PUBLISHED';
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;

-- No dynamic SQL or extra tables are needed for task-driven publication.
CREATE OR REPLACE PROCEDURE EDH_DEMO.GOVERNANCE.PUBLISH_LATEST(P_PRODUCT_ID VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER
AS
$$
DECLARE
  V_SOURCE VARCHAR;
  V_BATCH VARCHAR;
  V_EXISTS NUMBER DEFAULT 0;
  V_RESULT VARCHAR;
BEGIN
  IF (P_PRODUCT_ID IN ('shipment-reliability','freight-spend')) THEN
    V_SOURCE := 'Dispatch events';
  ELSEIF (P_PRODUCT_ID = 'returns-pulse') THEN
    V_SOURCE := 'Return events';
  ELSE
    RETURN 'UNKNOWN_PRODUCT';
  END IF;
  SELECT COUNT(*) INTO :V_EXISTS FROM EDH_DEMO.RAW.EVENTS
    WHERE SOURCE_ID = :V_SOURCE;
  IF (V_EXISTS = 0) THEN
    RETURN 'NO_SOURCE_DATA';
  END IF;
  SELECT BATCH_ID INTO :V_BATCH FROM EDH_DEMO.RAW.EVENTS
    WHERE SOURCE_ID = :V_SOURCE
    GROUP BY BATCH_ID ORDER BY MAX(LOADED_AT) DESC, BATCH_ID DESC LIMIT 1;
  CALL EDH_DEMO.GOVERNANCE.PUBLISH_PRODUCT(:P_PRODUCT_ID,:V_BATCH) INTO :V_RESULT;
  RETURN V_RESULT;
END;
$$;

GRANT USAGE ON PROCEDURE EDH_DEMO.GOVERNANCE.PUBLISH_PRODUCT(VARCHAR,VARCHAR)
  TO ROLE EDH_PUBLISHER;
GRANT USAGE ON PROCEDURE EDH_DEMO.GOVERNANCE.PUBLISH_LATEST(VARCHAR)
  TO ROLE EDH_PUBLISHER;

-- Native Snowflake Tasks replace Dagster scheduling. All start SUSPENDED.
CREATE TASK IF NOT EXISTS EDH_DEMO.GOVERNANCE.DAILY_SHIPMENT_RELIABILITY
  WAREHOUSE = EDH_DEMO_WH
  SCHEDULE = 'USING CRON 0 6 * * * UTC'
AS CALL EDH_DEMO.GOVERNANCE.PUBLISH_LATEST('shipment-reliability');
CREATE TASK IF NOT EXISTS EDH_DEMO.GOVERNANCE.DAILY_FREIGHT_SPEND
  WAREHOUSE = EDH_DEMO_WH
  SCHEDULE = 'USING CRON 20 6 * * * UTC'
AS CALL EDH_DEMO.GOVERNANCE.PUBLISH_LATEST('freight-spend');
CREATE TASK IF NOT EXISTS EDH_DEMO.GOVERNANCE.DAILY_RETURNS_PULSE
  WAREHOUSE = EDH_DEMO_WH
  SCHEDULE = 'USING CRON 40 6 * * * UTC'
AS CALL EDH_DEMO.GOVERNANCE.PUBLISH_LATEST('returns-pulse');

